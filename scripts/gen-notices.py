#!/usr/bin/env python3
"""Regenerate THIRD-PARTY-NOTICES.md from `cargo metadata` for the Windows target.

Needs Python 3 and cargo (run from WSL or Windows; the crates must be fetchable).
Usage: python3 scripts/gen-notices.py

Lists every crate that is linked into pulse-native for x86_64-pc-windows-msvc (normal dependencies only,
build tools are not shipped), with its license, then the license texts found in each crate's source,
grouped so identical texts appear once.
Prints a summary of crates whose license is copyleft-only or unclear.
The hand-written head of the file lives in scripts/notices-head.md.
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = "x86_64-pc-windows-msvc"
ROOT_PKG = "pulse-native"
COPYLEFT = re.compile(r"(A?GPL|LGPL|MPL|EPL|CDDL|OSL|EUPL)", re.I)
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|UNLICENSE|NOTICE)", re.I)


def metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET, "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped(meta: dict) -> list[dict]:
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    start = next(p["id"] for p in meta["packages"] if p["name"] == ROOT_PKG)
    seen, stack = set(), [start]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for dep in nodes[cur]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    seen.discard(start)
    members = set(meta["workspace_members"])
    return sorted((pkgs[i] for i in seen if i not in members), key=lambda p: (p["name"], p["version"]))


def classify(expr: str | None) -> str:
    """ok, copyleft (every alternative is copyleft) or unclear."""
    if not expr:
        return "unclear"
    if "LicenseRef-Slint-Royalty-free" in expr:
        return "ok"  # Slint: used under its royalty-free license, described in the head of the file
    alts = [a.strip(" ()") for a in re.split(r"\s+OR\s+|/", expr)]
    if any("LicenseRef" in a for a in alts) and not any(re.search(r"MIT|Apache|BSD|ISC|Zlib|Unlicense|CC0|Unicode", a) for a in alts):
        return "unclear"
    if all(COPYLEFT.search(a) for a in alts):
        return "copyleft"
    return "ok"


def license_texts(pkg: dict) -> list[tuple[str, str]]:
    base = Path(pkg["manifest_path"]).parent
    found = []
    for f in sorted(base.iterdir()):
        if f.is_file() and LICENSE_FILE.match(f.name):
            try:
                found.append((f.name, f.read_text(encoding="utf-8", errors="replace").strip()))
            except OSError:
                pass
    return found


def main() -> None:
    meta = metadata()
    crates = shipped(meta)
    head = (ROOT / "scripts/notices-head.md").read_text(encoding="utf-8").rstrip() + "\n"
    out = [head, "\n## Rust crates\n\n",
           f"{len(crates)} crates are linked into the Windows build.\n",
           "The list is generated by `scripts/gen-notices.py` from `cargo metadata` (do not edit it by hand).\n\n",
           "| Crate | Version | License |\n|---|---|---|\n"]
    flagged = []
    for p in crates:
        lic = p["license"] or (f"see {p['license_file']}" if p.get("license_file") else "UNSPECIFIED")
        out.append(f"| {p['name']} | {p['version']} | {lic.replace('|', '/')} |\n")
        c = classify(p["license"])
        if c != "ok":
            flagged.append((p["name"], p["version"], lic, c))

    groups: dict[str, dict] = {}
    for p in crates:
        for name, text in license_texts(p):
            h = hashlib.sha256(text.encode()).hexdigest()
            g = groups.setdefault(h, {"text": text, "crates": []})
            label = f"{p['name']} {p['version']}"
            if label not in g["crates"]:
                g["crates"].append(label)
    out.append("\n## License texts of the crates\n\n")
    out.append("Each block applies to the crates listed above it; identical texts are shown once.\n")
    for g in sorted(groups.values(), key=lambda g: g["crates"][0]):
        out.append("\n---\n\n" + ", ".join(g["crates"]) + "\n\n```text\n" + g["text"].replace("```", "'''") + "\n```\n")

    (ROOT / "THIRD-PARTY-NOTICES.md").write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"wrote THIRD-PARTY-NOTICES.md: {len(crates)} crates, {len(groups)} distinct license texts")
    print("copyleft or unclear:" if flagged else "no copyleft-only or unclear licenses")
    for f in flagged:
        print("  ", f)


if __name__ == "__main__":
    main()
